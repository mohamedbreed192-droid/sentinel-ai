import {test,expect} from '@playwright/test';
import path from 'node:path';
const shots=path.resolve(__dirname,'../../docs/screenshots');
test('dashboard, filtering, graph impact, assistant and export',async({page})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 await page.setViewportSize({width:1512,height:1120});
 await page.goto('/');await expect(page.locator('.app-shell')).toHaveAttribute('data-ready','true');
 await expect(page.getByRole('heading',{name:'Know your code. Reduce your risk.'})).toBeVisible();
 await expect(page.getByText('SYNTHETIC FIXTURE',{exact:true})).toBeVisible();
 await page.screenshot({path:path.join(shots,'overview.png'),fullPage:true});
 await page.getByRole('button',{name:'Security findings',exact:false}).first().click();
 await page.getByLabel('Search findings').fill('eval');
 await expect(page.locator('tbody tr')).toHaveCount(2);
 await page.getByLabel('Search findings').fill('');
 await page.getByLabel('Filter severity').selectOption('low');
 await expect(page.locator('tbody tr')).toHaveCount(3);
 await page.getByLabel('Filter severity').selectOption('all');
 await page.screenshot({path:path.join(shots,'security-findings.png'),fullPage:true});
 await page.getByRole('button',{name:'Digital twin',exact:false}).first().click();
 await page.getByRole('button',{name:'service.py',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Potentially affected modules'})).toBeVisible();
 await expect(page.locator('.impact code')).toHaveCount(2);
 await page.screenshot({path:path.join(shots,'digital-twin.png'),fullPage:true});
 await page.getByRole('button',{name:'AI assistant',exact:true}).click();
 await page.getByLabel('Assistant finding').selectOption({label:'Dynamic code evaluation · service.py:5'});
 await page.getByRole('button',{name:'Explain & recommend'}).click();
 await expect(page.locator('.explanation')).toContainText('No fix has been applied or verified');
 await expect(page.locator('pre').first()).toContainText('ast.literal_eval(value)');
 await page.screenshot({path:path.join(shots,'assistant.png'),fullPage:true});
 const downloaded=page.waitForEvent('download');
 await page.getByRole('button',{name:'Export report'}).click();
 expect((await downloaded).suggestedFilename()).toBe('sentinel-report.md');
 await page.getByRole('button',{name:'Dependencies',exact:true}).click();
 await expect(page.getByText('not applicable',{exact:true})).toHaveCount(2);
 await page.getByRole('button',{name:'Analyze repository',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.getByRole('button',{name:'Close dialog'}).click();
 expect(errors).toEqual([]);
});
test('mobile layout stays within viewport',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/');await expect(page.locator('.app-shell')).toHaveAttribute('data-ready','true');
 await expect(page.getByRole('heading',{name:'Know your code. Reduce your risk.'})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 await page.screenshot({path:path.join(shots,'mobile.png'),fullPage:true});
});
